import { GoogleGenAI } from '@google/genai';
import { CURATED_STOCK_PHOTOS } from '../src/data/curatedStockPhotos.js';
import { engineTimeout, isEngineCeiling, readEngineJson } from './engine.js';
import {
  DEFAULT_MODEL,
  ENGINE_MODELS,
  MODEL_ATTEMPT_TIMEOUT_MS,
  preferredModelFrom,
} from './routes/caption.js';

export interface IdeaBlueprint {
  focus: string;
  why: string;
  formats: string[];
  hook: string;
  /** The engine's own read on its hook, 0-100. 0 means nothing rated it — never a made-up number. */
  hookScore: number;
  beats: { label: string; time: string; body: string }[];
}

export interface GeneratedIdea {
  id: string;
  category: string;
  categoryTone: 'tertiary' | 'primary' | 'secondary' | 'neutral';
  title: string;
  excerpt: string;
  format: string;
  metric: string;
  thumb: string;
  imageId: string;
  imageAlt: string;
  blueprint: IdeaBlueprint;
}

/**
 * The same six library records the client resolves, so an idea generated by the model and one
 * scaffolded offline render the same photo with the same caption. The ids used here before were
 * `unsplash.com/photos/<slug>/download` links, which now 401 behind a bot check and were never in
 * the CSP's img-src — every card rendered empty.
 */
const CARD_PHOTO_IDS = ['curated-ws-3', 'curated-ws-4', 'curated-ws-1', 'curated-neon-2', 'curated-life-3', 'curated-life-4'];
const CURATED_IMAGES = CARD_PHOTO_IDS.map((id) => {
  const photo = CURATED_STOCK_PHOTOS.find((p) => p.id === id) ?? CURATED_STOCK_PHOTOS[0];
  return { id: photo.id, alt: photo.description };
});

function getGeminiClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return null;
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'kontentos-redesign',
      },
    },
  });
}

/** Scores are only kept when the engine supplied one; a random number here would be a fake measurement. */
function scoreOf(raw: unknown): number {
  const n = Number(raw);
  return Number.isFinite(n) && n > 0 && n <= 100 ? Math.round(n) : 0;
}

export async function generateIdeas(
  topic?: string,
  niche = 'Studio & SaaS',
  opts: { tone?: string; context?: string; temperature?: number; model?: string } = {}
): Promise<GeneratedIdea[]> {
  const query = (topic || '').trim();
  const ai = getGeminiClient();
  const brandVoice = String(opts.context || '').trim();
  const tone = String(opts.tone || '').trim() || 'Viral & Punchy';
  const temperature = Number.isFinite(Number(opts.temperature))
    ? Math.min(1, Math.max(0, Number(opts.temperature)))
    : 0.7;

  if (ai && query) {
    try {
      const prompt = `You are an elite short-form video creator, scriptwriter, and viral content strategist.
Given the topic "${query}", niche "${niche}" and tone "${tone}", generate 6 unique, scroll-stopping content ideas and detailed blueprints.

Categories to cover across the 6 ideas:
1. Trending Sprint (categoryTone: "tertiary")
2. High Potential (categoryTone: "primary")
3. Your Niche (categoryTone: "secondary")
4. Transparent Studio (categoryTone: "neutral")
5. Metric Runbook (categoryTone: "primary")
6. Evergreen (categoryTone: "neutral")

For each idea, return:
- title: punchy, compelling title (under 60 chars)
- excerpt: one concise sentence summarizing the core angle
- category: one of the 6 categories above
- categoryTone: matching categoryTone
- format: suggested duration/format (e.g. "Reel · 30 sec", "Carousel · 7 slides", "Short · 45s")
- metric: a short label for the angle, 24 characters or fewer
- blueprint:
  - focus: angle archetype (e.g. "Contrarian Focus", "Operator Playbook", "BTS Breakdown")
  - why: 2 sentences explaining why this works psychologically on the viewer
  - formats: array of 3-4 formats (e.g. ["Reel (30s)", "Carousel", "LinkedIn Post", "Short"])
  - hook: exact opening spoken hook in quotation marks (must stop the scroll in 3 seconds)
  - hookScore: your own read of that hook from 0 to 100. The app shows it as an estimate, never as a measurement — so give it only if you can argue for it.
  - beats: array of 3 timed beats with { label: "Beat 1: The Trap", time: "0:00 - 0:04", body: "visual + spoken action" }

Ground every claim in what the creator can actually show. Do not invent audience numbers, revenue,
time saved, or percentages about this niche's performance.

Return STRICTLY a JSON array of 6 idea objects with NO markdown formatting, NO backticks.` +
        (brandVoice
          ? `\n\nWrite as this specific creator, not as a generic strategist:\n${brandVoice}`
          : '');

      // Same cascade the copy engines use, so a seed, a script and a caption cannot disagree about
      // which engine is trustworthy — and each attempt is bounded.
      const modelsToTry = Array.from(
        new Set([preferredModelFrom(opts.model) ?? DEFAULT_MODEL, ...ENGINE_MODELS])
      );
      for (const model of modelsToTry) {
        let text = '';
        try {
          const res = await engineTimeout(
            ai.models.generateContent({
              model,
              contents: prompt,
              config: {
                responseMimeType: 'application/json',
                temperature,
              },
            }),
            MODEL_ATTEMPT_TIMEOUT_MS,
            `Timeout with model ${model}`
          );
          text = res.text?.trim() || '';
        } catch (mErr: any) {
          if (isEngineCeiling(mErr?.message)) {
            console.warn(`[ideasEngine] ${model} hit its ceiling — writing scaffolds instead of stacking timeouts:`, mErr?.message);
            break;
          }
          console.warn(`[ideasEngine] ${model} unavailable, trying next engine:`, mErr?.message);
          continue;
        }
        const answer = readEngineJson<any>(text);
        const parsed = Array.isArray(answer) && answer.length > 0 ? answer : null;
        if (!parsed) {
          console.warn(`[ideasEngine] ${model} returned an unusable answer, trying next engine.`);
          continue;
        }
        // A card with neither a title nor a hook is not an idea, and filling that gap with generator
        // boilerplate would pass off template text as the engine's thinking.
        const usable = parsed.filter((item: any) => item && (item.title || item.blueprint?.hook));
        if (usable.length === 0) {
          console.warn(`[ideasEngine] ${model} answered, but with nothing usable on any card.`);
          continue;
        }
        return usable.map((item: any, idx: number) => ({
          id: `idea-${Date.now()}-${idx}`,
          category: item.category || 'High Potential',
          categoryTone: item.categoryTone || 'primary',
          title: item.title || `[${query} — angle the engine named in its hook]`,
          excerpt: item.excerpt || '[why this angle, in one line — the engine left it to you]',
          format: item.format || 'Reel · 30 sec',
          metric: item.metric || 'From the engine',
          thumb: String.fromCharCode(97 + (idx % 6)), // 'a' through 'f'
          imageId: CURATED_IMAGES[idx % CURATED_IMAGES.length].id,
          imageAlt: CURATED_IMAGES[idx % CURATED_IMAGES.length].alt,
          blueprint: {
            focus: item.blueprint?.focus || 'Strategic Angle',
            why: item.blueprint?.why || '[the engine gave no reason — decide whether this angle is yours before shooting]',
            formats: item.blueprint?.formats || ['Reel (30s)', 'Carousel', 'LinkedIn Post'],
            hook: item.blueprint?.hook || '[opening line the engine did not write]',
            hookScore: scoreOf(item.blueprint?.hookScore),
            beats: item.blueprint?.beats?.length
              ? item.blueprint.beats
              : [{ label: 'Beat 1', time: '[start]', body: '[the engine named no beats — block the shape yourself]' }],
          },
        }));
      }
    } catch (err) {
      console.warn('Gemini ideas generation notice: writing scaffolds instead', err);
    }
  }

  return generateScaffoldIdeas(query, niche);
}

// The no-engine answer: structures, not copy. Nothing here is a finished hook and no claim is
// attached to the creator's niche — every bracket is a line they fill from their own work.
