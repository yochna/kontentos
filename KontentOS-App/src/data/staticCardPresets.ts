/**
 * Returns the resolved typography bundle with backward compatibility aliases.
 */
export function getTypographyBundle(style?: FontStyle): TypographyBundle {
  if (!style) return TYPOGRAPHY_BUNDLES['modern-grotesk'];

  // Backward-compatibility aliases
  if (style === 'grotesk') return TYPOGRAPHY_BUNDLES['modern-grotesk'];
  if (style === 'editorial') return TYPOGRAPHY_BUNDLES['editorial-serif'];
  if (style === 'mono') return TYPOGRAPHY_BUNDLES['punchy-mono'];
  if (style === 'serif') return TYPOGRAPHY_BUNDLES['classic-literature'];

  return TYPOGRAPHY_BUNDLES[style] || TYPOGRAPHY_BUNDLES['modern-grotesk'];
}
