/**
 * Derives active ThemeConfig dynamically, seamlessly injecting user custom accents
 * and adjusting glowing highlights and borders.
 */
export function getActiveTheme(state: { theme: string; customAccent?: string }): ThemeConfig {
  const baseTheme = THEME_CONFIGS[state.theme] || THEME_CONFIGS['midnight-cyan'];
  if (!state.customAccent) return baseTheme;

  const hex = state.customAccent;
  const isLight = baseTheme.mode === 'light';

  return {
    ...baseTheme,
    accent: hex,
    accentGradient: `linear-gradient(135deg, ${hex} 0%, ${hex}dd 100%)`,
    borderColor: isLight ? `${hex}55` : `${hex}66`,
    glowColor: `${hex}40`,
    pillBg: isLight ? `${hex}18` : `${hex}26`,
    pillText: hex,
  };
}

